// Як людина вводить слово: регістр, пробіли, різні апострофи й латинські «двійники» не важливі.
const LOOKALIKE = { A: "А", B: "В", C: "С", E: "Е", H: "Н", I: "І", K: "К", M: "М", O: "О", P: "Р", T: "Т", X: "Х", Y: "У" };
export const normalizeWord = (s) =>
  String(s ?? "").toUpperCase().replace(/[ABCEHIKMOPTXY]/g, (c) => LOOKALIKE[c]).replace(/[^А-ЯҐЄІЇ]/g, "");

// → слово дня (у верхньому регістрі, як у списку).
export async function cipherWord(day, secret) {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(`cipher:${secret}:${day}`));
  return WORDS[new DataView(digest).getUint32(0) % WORDS.length];
}

export async function isCipher(guess, day, secret) {
  return normalizeWord(guess) === normalizeWord(await cipherWord(day, secret));
}

